CREATE TABLE IF NOT EXISTS customer_applications (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    application_reference VARCHAR(32) NOT NULL UNIQUE,
    customer_user_id INT NOT NULL,
    product_id INT NOT NULL,
    location_id INT NOT NULL,
    status ENUM('submitted', 'under_review', 'approved', 'rejected', 'completed', 'cancelled') NOT NULL DEFAULT 'submitted',
    quantity INT NOT NULL,
    customer_name VARCHAR(255) NOT NULL,
    contact_number VARCHAR(50) NOT NULL,
    address VARCHAR(500) NOT NULL,
    purpose VARCHAR(500) NOT NULL,
    notes VARCHAR(1000) NULL,
    rejection_reason VARCHAR(500) NULL,
    reviewed_by_user_id INT NULL,
    reviewed_at TIMESTAMP NULL,
    completed_by_user_id INT NULL,
    completed_at TIMESTAMP NULL,
    cancelled_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_customer_applications_customer FOREIGN KEY (customer_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_applications_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_applications_location FOREIGN KEY (location_id) REFERENCES locations(id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_applications_reviewed_by FOREIGN KEY (reviewed_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_applications_completed_by FOREIGN KEY (completed_by_user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_customer_applications_quantity_positive CHECK (quantity > 0),
    INDEX idx_customer_applications_customer (customer_user_id),
    INDEX idx_customer_applications_product (product_id),
    INDEX idx_customer_applications_location (location_id),
    INDEX idx_customer_applications_status (status),
    INDEX idx_customer_applications_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
